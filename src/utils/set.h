bool svset_keyExistsFromLiteral(StringViewSet* svs, const char* key);

////////////////////////////////////////////////////////////////////////////////
/// Insert
bool svset_insert(StringViewSet* svs, StringView key);

////////////////////////////////////////////////////////////////////////////////
/// Delete
void svset_delete(StringViewSet* svs, StringView key);
